"""Digit-corruption experiment in which a GRU suggests denominators and
exact arithmetic checks them against the observation cell, widened until a
candidate fits, alongside non-learned baselines.  Needs PyTorch (the
library and demo.py use only the standard library).

    python hybrid_gru.py --noise 0.1 --seed 0        # one run
    for s in 0 1 2; do python hybrid_gru.py --noise 0.1 --seed "$s"; done

Protocol (regenerates results/q100_k12_*.json):
* Population: all reduced p/q with 0 < p < q <= qmax, split 80/10/10 by
  fraction.  No test fraction appears in training, so the evaluation
  measures generalisation to unseen fractions.  Denominators are not held
  out, and with qmax = 100 and split 0 every test denominator except 2
  also occurs in training (1/2, the only fraction with q = 2, is in the
  test set).
* ``--split-seed`` sets the data split and is separate from ``--seed``,
  which varies model initialisation and the training and evaluation
  corruptions.  Holding the split fixed keeps clean-vs-noisy comparisons
  paired, and the reported spread is then run-to-run variation on that one
  split.
* Within each run, all methods are evaluated on the same corrupted rows.
  The classical baseline widens its cell until candidates appear (the slack
  ladder, up to 2e11 ulps, i.e. +/-0.2 at 12 digits).  The hybrid
  restricts exact reconstruction to the GRU's top-5 denominator proposals,
  widening the cell by the same slack ladder, and falls back to the
  classical baseline if no proposal fits.  Under corruption its exact check
  is therefore a check against the widened cell.  A proposed q admits any
  fraction whose reduced denominator divides q.  Both rank with the prior
  exponent s = 2 (the library default) and are also scored with s = 0,
  which matches the uniform draw of test fractions.
* Two further decoders need no training.  The oracle hybrid is the hybrid
  given the true denominator as its only proposal, scored with s = 2 and
  with s = 0, so it measures the verifier rather than the GRU.  The
  nearest-codeword decoder returns the fraction whose 12 rounded digits
  differ from the observed ones in the fewest positions, with ties going
  to the smallest denominator and then the smallest numerator.  Under this
  corruption a candidate at Hamming distance d has likelihood
  0.91^(12-d) * 0.01^d, so with a uniform prior on the fractions this
  decoder is maximum a posteriori.  The metric nearest_codeword_unique_top1
  counts every tie as a miss.
* noisy_input_counts gives, summed over the evaluation draws, the number
  of corrupted inputs, how many have more than one nearest codeword, how
  many have a changed digit in the first three places, and how many of
  those the classical baseline (s = 2) and the nearest-codeword decoder
  recover, the latter also with every tie counted as a miss.

Result reproduced by this script (a pilot with qmax = 100, one
architecture, three seeds and split 0): under 10% per-digit corruption
(a digit actually changes with probability 0.09), exact-fraction top-1 is
0.685 +/- 0.008 for the classical baseline and 0.703 +/- 0.007 for the
hybrid, but 0.945 +/- 0.004 for the nearest-codeword decoder, so at this
scale the learned component is not needed.  On clean digits the hybrid
scores about 0.003 below the exact optimum of 1.  See THEORY 7.2 for the
interpretation and limitations of these results.
"""
from __future__ import annotations

import argparse
import json
import math
import random
from fractions import Fraction
from pathlib import Path

try:
    import torch
    from torch import nn
except ModuleNotFoundError as exc:  # pragma: no cover
    raise SystemExit("this experiment needs PyTorch:  pip install torch") from exc

from ratrecon import decimal_digits, reconstruct, sufficient_digits

SLACK_LADDER = [0.0] + [2.0 * 10 ** i for i in range(12)]


class DenominatorGRU(nn.Module):
    """GRU that maps a digit sequence to the class q - 2 (about 45k
    parameters).  The digits are generated by the hidden residues
    p*10^i mod q, so recovering q is a hard sequence task for a small
    recurrent model."""

    def __init__(self, qmax: int, emb: int = 24, hidden: int = 96):
        super().__init__()
        self.embed = nn.Embedding(10, emb)
        self.gru = nn.GRU(emb, hidden, batch_first=True)
        self.head = nn.Linear(hidden, qmax - 1)

    def forward(self, digits):
        h, _ = self.gru(self.embed(digits))
        return self.head(h[:, -1])


def make_splits(qmax: int, k: int, seed: int):
    fracs = [
        (p, q) for q in range(2, qmax + 1) for p in range(1, q) if math.gcd(p, q) == 1
    ]
    random.Random(seed).shuffle(fracs)
    n = len(fracs)
    parts = {
        "train": fracs[: int(0.8 * n)],
        "val": fracs[int(0.8 * n) : int(0.9 * n)],
        "test": fracs[int(0.9 * n) :],
    }
    out = {}
    for name, fs in parts.items():
        rows = [[int(c) for c in decimal_digits(Fraction(p, q), k)[2:]] for p, q in fs]
        out[name] = {
            "fracs": fs,
            "x": torch.tensor(rows, dtype=torch.int64),
            "y": torch.tensor([q - 2 for _, q in fs], dtype=torch.int64),
        }
    return out


def corrupt(x, rho: float, gen):
    """Replace each digit independently, with probability rho, by a uniform
    random digit.  The new digit can equal the old one, so a digit changes
    with probability 0.9 * rho."""
    if rho <= 0:
        return x
    mask = torch.rand(x.shape, generator=gen) < rho
    return torch.where(mask, torch.randint(0, 10, x.shape, generator=gen), x)


def classical_predict(row, qmax: int, s: float = 2.0) -> Fraction:
    text = "0." + "".join(str(int(d)) for d in row)
    for slack in SLACK_LADDER:
        cands = reconstruct(text, qmax=qmax, noise_ulp=slack, max_candidates=8,
                            include_lattice=False, prior_exponent=s)
        if cands:
            return cands[0].fraction
    return Fraction(0)


def hybrid_predict(row, hint_qs, qmax: int, s: float = 2.0) -> Fraction:
    text = "0." + "".join(str(int(d)) for d in row)
    for slack in SLACK_LADDER:
        cands = reconstruct(text, qmax=qmax, noise_ulp=slack, max_candidates=5,
                            include_lattice=False, include_periodic=False,
                            denominators=hint_qs, prior_exponent=s)
        if cands:
            return cands[0].fraction
    return classical_predict(row, qmax, s)


def make_codebook(qmax: int, k: int):
    """All reduced p/q in (0, 1) with q <= qmax, sorted by (q, p), and their
    k rounded digits.  The sort order makes argmin break ties towards the
    smallest denominator, then the smallest numerator."""
    fracs = [(p, q) for q in range(2, qmax + 1) for p in range(1, q) if math.gcd(p, q) == 1]
    rows = [[int(c) for c in decimal_digits(Fraction(p, q), k)[2:]] for p, q in fracs]
    return fracs, torch.tensor(rows, dtype=torch.int64)


def exact_eval(x, hints_per_row, true_fracs, qmax: int, codebook, clean=None):
    """Top-1 rates of every decoder on the rows of x.  If the uncorrupted
    rows are given as clean, the counts described under noisy_input_counts
    are returned as well."""
    book, words = codebook
    m = dict.fromkeys(["cls_f", "hyb_f", "cls_q", "hyb_q", "cls0_f", "hyb0_f",
                       "oracle_f", "oracle0_f", "near_f", "near_unique"], 0)
    counts = dict.fromkeys(["inputs", "nearest_codeword_ties", "changed_in_first_three",
                            "classical_correct_there", "nearest_codeword_correct_there",
                            "nearest_codeword_unique_correct_there"], 0)
    for i, (row, hints, (p, q)) in enumerate(zip(x.tolist(), hints_per_row, true_fracs)):
        truth = Fraction(p, q)
        dist = (x[i] != words).sum(-1)  # Hamming distance to every codeword
        nearest = int(dist.argmin())  # first minimum, i.e. smallest (q, p)
        c, h = classical_predict(row, qmax), hybrid_predict(row, hints, qmax)
        m["cls_f"] += c == truth
        m["hyb_f"] += h == truth
        m["cls_q"] += c.denominator == q
        m["hyb_q"] += h.denominator == q
        m["cls0_f"] += classical_predict(row, qmax, s=0.0) == truth
        m["hyb0_f"] += hybrid_predict(row, hints, qmax, s=0.0) == truth
        m["oracle_f"] += hybrid_predict(row, [q], qmax) == truth
        m["oracle0_f"] += hybrid_predict(row, [q], qmax, s=0.0) == truth
        hit = book[nearest] == (p, q)
        unique = int((dist == dist[nearest]).sum()) == 1
        m["near_f"] += hit
        m["near_unique"] += hit and unique
        if clean is not None:
            early = bool((x[i, :3] != clean[i, :3]).any())
            counts["inputs"] += 1
            counts["nearest_codeword_ties"] += not unique
            counts["changed_in_first_three"] += early
            counts["classical_correct_there"] += early and c == truth
            counts["nearest_codeword_correct_there"] += early and hit
            counts["nearest_codeword_unique_correct_there"] += early and hit and unique
    n = len(true_fracs)
    out = {"classical_q_top1": m["cls_q"] / n, "classical_fraction_top1": m["cls_f"] / n,
           "hybrid_q_top1": m["hyb_q"] / n, "hybrid_fraction_top1": m["hyb_f"] / n,
           "classical_s0_fraction_top1": m["cls0_f"] / n,
           "hybrid_s0_fraction_top1": m["hyb0_f"] / n,
           "oracle_hybrid_fraction_top1": m["oracle_f"] / n,
           "oracle_hybrid_s0_fraction_top1": m["oracle0_f"] / n,
           "nearest_codeword_fraction_top1": m["near_f"] / n,
           "nearest_codeword_unique_top1": m["near_unique"] / n}
    if clean is not None:
        out["counts"] = counts
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--qmax", type=int, default=100)
    ap.add_argument("--digits", type=int, default=12)
    ap.add_argument("--noise", type=float, default=0.1)
    ap.add_argument("--epochs", type=int, default=30)
    ap.add_argument("--batch", type=int, default=256)
    ap.add_argument("--aug", type=int, default=6)
    ap.add_argument("--eval-draws", type=int, default=5)
    ap.add_argument("--seed", type=int, default=0,
                    help="weights and corruption (the split uses --split-seed)")
    ap.add_argument("--split-seed", type=int, default=0)
    ap.add_argument("--output-dir", type=Path, default=Path("results"))
    args = ap.parse_args()
    if args.qmax < 5:
        ap.error("--qmax must be >= 5 (a smaller value leaves a split empty)")
    if not 0.0 <= args.noise <= 1.0:
        ap.error("--noise is a probability")

    torch.manual_seed(args.seed)
    gen = torch.Generator().manual_seed(args.seed)
    sp = make_splits(args.qmax, args.digits, args.split_seed)
    codebook = make_codebook(args.qmax, args.digits)
    x_tr, y_tr = sp["train"]["x"], sp["train"]["y"]
    x_va, y_va = sp["val"]["x"], sp["val"]["y"]
    x_te, y_te = sp["test"]["x"], sp["test"]["y"]
    print(f"train={len(y_tr)} val={len(y_va)} test={len(y_te)} fractions  "
          f"(threshold k* = {sufficient_digits(args.qmax)}, k = {args.digits})")

    model = DenominatorGRU(args.qmax)
    opt = torch.optim.Adam(model.parameters(), lr=2e-3)
    loss_fn = nn.CrossEntropyLoss()
    for epoch in range(1, args.epochs + 1):
        model.train()
        xs = corrupt(x_tr.repeat(args.aug, 1), args.noise, gen)  # fresh corruption = augmentation
        ys = y_tr.repeat(args.aug)
        perm = torch.randperm(len(ys), generator=gen)
        xs, ys = xs[perm], ys[perm]
        for i in range(0, len(ys), args.batch):
            opt.zero_grad()
            loss = loss_fn(model(xs[i : i + args.batch]), ys[i : i + args.batch])
            loss.backward()
            opt.step()
        if epoch % 5 == 0 or epoch == 1:
            model.eval()
            with torch.no_grad():
                va = (model(corrupt(x_va, args.noise, gen)).argmax(-1) == y_va).float().mean()
            print(f"  epoch {epoch}: train loss {loss.item():.3f}  val acc {va.item():.3f}")

    eval_gen = torch.Generator().manual_seed(args.seed + 12345)
    draws = [corrupt(x_te, args.noise, eval_gen) for _ in range(args.eval_draws)]
    model.eval()
    with torch.no_grad():
        lg = model(x_te)
        top_k = min(5, lg.shape[-1])
        metrics = {
            "config": {k: str(v) if isinstance(v, Path) else v for k, v in vars(args).items()},
            "rnn": {"clean_top1": (lg.argmax(-1) == y_te).float().mean().item(),
                    "clean_top5": (lg.topk(top_k, -1).indices == y_te[:, None])
                    .any(-1).float().mean().item()},
            "exact_clean": exact_eval(
                x_te, (lg.topk(top_k, -1).indices + 2).tolist(), sp["test"]["fracs"], args.qmax,
                codebook),
        }
        noisy = {k: 0.0 for k in metrics["exact_clean"]}
        counts = {}
        r1 = r5 = 0.0
        for xd in draws:
            lgd = model(xd)
            r1 += (lgd.argmax(-1) == y_te).float().mean().item() / len(draws)
            r5 += ((lgd.topk(top_k, -1).indices == y_te[:, None])
                   .any(-1).float().mean().item() / len(draws))
            ev = exact_eval(xd, (lgd.topk(top_k, -1).indices + 2).tolist(),
                            sp["test"]["fracs"], args.qmax, codebook, clean=x_te)
            for k in noisy:
                noisy[k] += ev[k] / len(draws)
            for k, v in ev["counts"].items():
                counts[k] = counts.get(k, 0) + v
        metrics["rnn"]["noisy_top1"], metrics["rnn"]["noisy_top5"] = r1, r5
        metrics["exact_noisy"] = noisy
        metrics["noisy_input_counts"] = counts

    args.output_dir.mkdir(parents=True, exist_ok=True)
    out = args.output_dir / (
        f"q{args.qmax}_k{args.digits}_noise{args.noise}_seed{args.seed}_split{args.split_seed}.json"
    )
    out.write_text(json.dumps(metrics, indent=2))
    print(json.dumps({k: metrics[k] for k in ("rnn", "exact_clean", "exact_noisy")}, indent=2))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
